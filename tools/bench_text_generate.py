    def block(self, nodes: list[ast.stmt], depth: int) -> str:
        out: list[str] = []
        lang = self.lang
        indent = "    " * depth
        semi = "" if lang in ("python", "jett") else ";"
        for n in nodes:
            if isinstance(n, ast.AnnAssign):
                assert isinstance(n.target, ast.Name)
                name, typ = n.target.id, type_name(n.annotation)
                self.vars[name] = typ
                value = self.expr(n.value)
                declaration = {"jett":f"mutable {self.typ(typ)} {name} = {value}", "python":f"{name}: {self.typ(typ)} = {value}", "typescript":f"let {name}: {self.typ(typ)} = {value}", "go":f"var {name} {self.typ(typ)} = {value}", "rust":f"let mut {name}: {self.typ(typ)} = {value}"}[lang]
                out.append(indent + declaration + semi)
            elif isinstance(n, ast.Assign):
                assert len(n.targets) == 1 and isinstance(n.targets[0], ast.Name)
                out.append(indent + n.targets[0].id + " = " + self.expr(n.value) + semi)
            elif isinstance(n, ast.Return):
                out.append(indent + "return " + self.expr(n.value) + semi)
            elif isinstance(n, (ast.If, ast.While)):
                word = "if" if isinstance(n, ast.If) else ("for" if lang == "go" else "while")
                test = self.expr(n.test)
                if lang == "typescript":
                    test = "(" + test + ")"
                end = ":" if lang in ("python", "jett") else " {"
                out.append(indent + word + " " + test + end)
                out.append(self.block(n.body, depth + 1))
                if lang not in ("python", "jett"):
                    out.append(indent + "}")
                if n.orelse:
                    out.append(indent + "else" + end)
                    out.append(self.block(n.orelse, depth + 1))
                    if lang not in ("python", "jett"):
                        out.append(indent + "}")
            else:
                raise ValueError(ast.dump(n))
        rendered = "\n".join(out)
        if lang == "go":
            rendered = re.sub(r"}\n\s*else", "} else", rendered)
        return rendered

    def function(self, f: ast.FunctionDef, signature: bool = False) -> str:
        self.vars = {a.arg: type_name(a.annotation) for a in f.args.args}
        args = [f"{a.arg}: {self.typ(type_name(a.annotation))}" for a in f.args.args]
        typ = self.typ(type_name(f.returns))
        if self.lang == "jett":
            head = f"function {f.name}({', '.join(args)}) returns {typ}"
        elif self.lang == "python":
            head = f"def {f.name}({', '.join(args)}) -> {typ}"
        elif self.lang == "typescript":
            head = f"export function {f.name}({', '.join(args)}): {typ}"
        elif self.lang == "go":
            args = [f"{a.arg} {self.typ(type_name(a.annotation))}" for a in f.args.args]
            head = f"func {f.name}({', '.join(args)}) {typ}"
        else:
            head = f"pub fn {f.name}({', '.join(args)}) -> {typ}"
        if signature:
            return head
        suffix = ":" if self.lang in ("python", "jett") else " {"
        body = self.block(f.body, 1)
        return head + suffix + "\n" + body + ("\n}" if self.lang not in ("python", "jett") else "")

