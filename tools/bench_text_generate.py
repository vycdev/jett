def format_sources() -> None:
    """Keep regenerated native sources in their standard formatting."""
    jett = ROOT / "target/debug" / ("jett.exe" if __import__("os").name == "nt" else "jett")
    for item in TASKS:
        directory = ROOT / "benchmarks/tasks" / ("text_" + item.name)
        if jett.is_file():
            for filename in ("baseline.jett", "hidden.jett"):
                subprocess.run([str(jett), "format", str(directory / filename)], check=True, capture_output=True, text=True)
        if shutil.which("gofmt"):
            subprocess.run(["gofmt", "-w", str(directory / "baseline.go"), str(directory / "hidden_test.go")], check=True)
        if shutil.which("rustfmt"):
            subprocess.run(["rustfmt", "--edition", "2024", str(directory / "baseline.rs"), str(directory / "hidden.rs")], check=True)

def make_hidden(item: Task, lang: str, kind: str) -> str:
    checks: list[str] = []
    for i, (args, expected) in enumerate(item.cases):
        expected = expected_value(item, expected)
        call = "solve(" + ", ".join(literal(v, lang) for v in args) + ")"
        if kind == "Outcome":
            tag, value = expected
            if lang == "jett":
                call = "hidden_outcome(" + call + ")"
                encoded = str(value)
                if isinstance(value, list):
                    encoded = "".join(str(len(v)) + ":" + v for v in value)
                wanted = literal(tag + ":" + encoded, lang)
            elif lang == "python":
                wanted = f"TextAccepted({literal(value, lang)})" if tag == "accepted" else "TextRejected(TextError." + value.upper() + ")"
            elif lang == "typescript":
                wanted = '{kind: "accepted", value: ' + literal(value, lang) + '}' if tag == "accepted" else '{kind: "rejected", error: ' + literal(value, lang) + '}'
            elif lang == "go":
                wanted = 'TextAccepted{Value: ' + literal(value, lang) + '}' if tag == "accepted" else 'TextRejected{Error: ' + value.title() + '}'
            else:
                wanted = 'TextOutcome::Accepted(' + literal(value, lang) + ')' if tag == "accepted" else 'TextOutcome::Rejected(TextError::' + value.title() + ')'
        elif kind == "Pair":
            a, b = expected
            if lang == "jett":
                call = "hidden_pair(" + call + ")"
                wanted = literal(str(len(a))+":"+a+str(len(b))+":"+b, lang)
            elif lang == "python":
                wanted = f"TextPair({literal(a, lang)}, {literal(b, lang)})"
            elif lang == "typescript":
                wanted = f"{{first: {literal(a, lang)}, second: {literal(b, lang)}}}"
            elif lang == "go":
                wanted = f"TextPair{{First: {literal(a, lang)}, Second: {literal(b, lang)}}}"
            else:
                wanted = f"TextPair {{first: {literal(a, lang)}, second: {literal(b, lang)}}}"
        else:
            wanted = literal(expected, lang)
            if lang == "go" and kind == "int":
                wanted = f"int64({wanted})"
        checks.append({"jett":f"    assert {call} == {wanted}", "python":f"assert {call} == {wanted}, {i}", "typescript":f"check({call}, {wanted}, {i});", "go":f"    if got := {call}; !reflect.DeepEqual(got, {wanted}) {{ t.Fatalf(\"case {i}: got %#v\", got) }}", "rust":f"    assert_eq!({call}, {wanted}, \"case {i}\");"}[lang])
    if lang == "jett":
        head = ""
        if item.name == "escape_json_string":
            head = '''function hidden_ascii(text: string) returns string:
    bytes encoded = bytes.from_hex(text) handle error:
        return ""
    string decoded = bytes.to_string(view encoded) handle error:
        return ""
    return decoded
'''
        if kind == "Outcome":
            head = '''function hidden_error(error: TextError) returns string:
    match error:
        empty:
            return "empty"
        malformed:
            return "malformed"
        range:
            return "range"
function hidden_outcome(outcome: TextOutcome) returns string:
    match outcome:
        accepted(value):
            return "accepted:{value}"
        rejected(error):
            return "rejected:{hidden_error(error)}"
'''
            if payload_kind(item) == "Words":
                head = '''function hidden_words(values: list[string]) returns string:
    mutable string encoded = ""
    for value in values:
        encoded = "{encoded}{string.length(value)}:{value}"
    return encoded
''' + head.replace('return "accepted:{value}"', 'return "accepted:{hidden_words(value)}"')
        if kind == "Pair":
            head = '''function hidden_pair(value: TextPair) returns string:
    return "{string.length(value.first)}:{value.first}{string.length(value.second)}:{value.second}"
'''
        # Verify bodies have bounded statement counts: one block per case.
        return head + "\n".join(f"verify hidden_case_{i}:\n{check}" for i, check in enumerate(checks)) + "\n"
    if lang == "python":
        imports = "solve" + (", TextAccepted, TextRejected, TextError" if kind == "Outcome" else ", TextPair" if kind == "Pair" else "")
        return "from solution import " + imports + "\n\n" + "\n".join(checks) + "\n"
    if lang == "typescript":
        typ = TYPES[lang][kind]
        imports = ", type " + typ if kind in ("Outcome", "Pair") else ""
        compare = "got !== want"
        if kind == "Pair":
            compare = "got.first !== want.first || got.second !== want.second"
        if kind == "Outcome":
            compare = 'got.kind !== want.kind || (got.kind === "accepted" && want.kind === "accepted" && got.value !== want.value) || (got.kind === "rejected" && want.kind === "rejected" && got.error !== want.error)'
            if payload_kind(item) == "Words":
                compare = compare.replace("got.value !== want.value", "(got.value.length !== want.value.length || want.value.some((v, p) => v !== got.value[p]))")
        return 'import { solve' + imports + ' } from "./solution.js";\n' + f"function check(got: {typ}, want: {typ}, index: number): void {{\n" + f'  if ({compare}) throw new Error(`case ${{index}}`);\n}}\n' + "\n".join(checks) + "\n"
    if lang == "go":
        return 'package benchmark\nimport ("testing"; "reflect")\nfunc TestHidden(t *testing.T) {\n' + "\n".join(checks) + "\n}\n"
    return 'include!("solution.rs");\n#[test]\nfn hidden_cases() {\n' + "\n".join(checks) + "\n}\n"

