def payload_kind(item: Task) -> str:
    return "int" if item.name in NUMERIC_TASKS else "Words" if item.name == "csv_record_parse" else "str"

class RemoveRender(ast.NodeTransformer):
    def visit_Call(self, node: ast.Call) -> ast.AST:
        self.generic_visit(node)
        if isinstance(node.func, ast.Name) and node.func.id == "accepted":
            arg = node.args[0]
            if isinstance(arg, ast.Call) and isinstance(arg.func, ast.Name) and arg.func.id == "render":
                node.args[0] = arg.args[0]
        return node

def expected_value(item: Task, expected: object) -> object:
    if item.name in NUMERIC_TASKS and expected[0] == "accepted":
        return ("accepted", int(expected[1]))
    return expected

def needed_functions(source: str) -> list[ast.FunctionDef]:
    all_nodes = ast.parse(HELPERS + source).body
    funcs = {n.name:n for n in all_nodes if isinstance(n, ast.FunctionDef)}
    needed = {"solve"}
    while True:
        new = set(needed)
        for name in needed:
            new.update(n.func.id for n in ast.walk(funcs[name]) if isinstance(n, ast.Call) and isinstance(n.func, ast.Name) and n.func.id in funcs)
        if new == needed:
            return [f for name,f in funcs.items() if name in needed]
        needed = new

def literal(value: object, lang: str) -> str:
    if isinstance(value, list):
        values = ", ".join(literal(v, lang) for v in value)
        return {"python":"[" + values + "]", "typescript":"[" + values + "]", "go":"[]string{" + values + "}", "rust":"vec![" + values + "]", "jett":"list(" + values + ")"}[lang]
    if isinstance(value, str):
        if lang == "jett" and any(ch in value for ch in ("\b", "\f")):
            return 'hidden_ascii("' + value.encode("ascii").hex() + '")'
        out = json.dumps(value)
        if lang == "jett":
            out = out.replace("{", "{{").replace("}", "}}")
        if lang == "rust":
            out = out.replace("\\b", "\\u{0008}").replace("\\f", "\\u{000c}") + ".to_string()"
        return out
    if isinstance(value, bool):
        return str(value) if lang == "python" else str(value).lower()
    return str(value)

def generate() -> None:
    template = json.loads((ROOT / "benchmarks/tasks/score_lines/task.json").read_text())
    for item in TASKS:
        directory = ROOT / "benchmarks/tasks" / ("text_" + item.name)
        directory.mkdir(exist_ok=True)
        funcs = needed_functions(item.source)
        if item.name in NUMERIC_TASKS:
            funcs = [RemoveRender().visit(f) for f in funcs]
        main = next(f for f in funcs if f.name == "solve")
        kind = type_name(main.returns)
        spec = {"id":"text_" + item.name, "version":"1.0.0", "title":item.name.replace("_", " ").capitalize(), "category":"text_parsing" if kind == "Outcome" else "text_transformation", "difficulty":"medium" if kind == "Outcome" or item.name in ("glob_match", "strip_line_comments", "path_normalize", "camel_to_snake", "wrap_words") else "easy", "statement":item.statement, "constraints":["All text is ASCII; unless a narrower task bound is stated, each input string has at most 1000 characters.", "Preserve the exact declared public types and solve signature. Helpers are allowed.", "No input/output, exception throwing, panic, tests, or static diagnostic suppression in the submitted source."], "adapters":{}}
        for lang, ext in LANGS.items():
            emitter = Emitter(lang, funcs)
            declarations = DECLS.get(kind, {}).get(lang, "")
            payload = payload_kind(item)
            if kind == "Outcome" and payload != "str":
                replacements = {"jett":("value: string", "value: " + TYPES[lang][payload]), "python":("value: str", "value: " + TYPES[lang][payload]), "typescript":("readonly value: string", "readonly value: " + TYPES[lang][payload]), "go":("Value string", "Value " + TYPES[lang][payload]), "rust":("Accepted(String)", "Accepted(" + TYPES[lang][payload] + ")")}
                old, new = replacements[lang]
                declarations = declarations.replace(old, new)
            prelude = PRELUDE[lang]
            if payload == "Words":
                prelude += LIST_PRELUDE[lang]
            if lang == "python" and kind not in ("Outcome", "Pair"):
                prelude = prelude.replace("from dataclasses import dataclass\nfrom enum import Enum\n", "")
            if lang == "python" and kind == "Pair":
                prelude = prelude.replace("from enum import Enum\n", "")
            baseline = prelude + "\n" + declarations + "\n" + "\n\n".join(emitter.function(f) for f in funcs) + "\n"
            # Python annotations use actual published type names too.
            baseline = baseline.replace(" -> Outcome:", " -> TextOutcome:").replace(" -> Pair:", " -> TextPair:")
            (directory / f"baseline.{ext}").write_text(baseline, newline="\n")
            signature_prefix = "namespace benchmark\n\n" if lang == "jett" else "package benchmark\n\n" if lang == "go" else "from dataclasses import dataclass\nfrom enum import Enum\n\n" if lang == "python" and kind in ("Outcome", "Pair") else ""
            adapter = copy.deepcopy(template["adapters"][lang])
            adapter["signature"] = signature_prefix + declarations + emitter.function(main, True)
            # Generic source restrictions; exhaustive matching is not required by these signatures.
            adapter["forbidden_patterns"] = [p for p in adapter.get("forbidden_patterns", []) if not ("catch-all" in p["message"] or "default switch" in p["message"] or "wildcard match" in p["message"])]
            if kind == "Outcome" and lang == "jett":
                adapter["forbidden_patterns"].append({"pattern": "(?m)^\\s*(?:other|_)\\s*:", "message":"catch-all match arms are forbidden; handle all declared enum variants explicitly"})
            for p in adapter["forbidden_patterns"]:
                p["message"] = p["message"].replace("return ScoreFailure", "use the declared return type").replace("return Failure", "use the declared return type").replace("return rejected", "use the declared return type")
            spec["adapters"][lang] = adapter
            if lang == "python":
                (directory / "pyrightconfig.json").write_text(json.dumps({"include":["solution.py", "hidden.py"],"pythonVersion":"3.12","typeCheckingMode":"strict"}, indent=2)+"\n", newline="\n")
            hidden = make_hidden(item, lang, kind)
            (directory / adapter["hidden"]).write_text(hidden, newline="\n")
        (directory / "task.json").write_text(json.dumps(spec, indent=2)+"\n", newline="\n")
        fixtures = []
        for args, expected in item.cases:
            expected = expected_value(item, expected)
            outcome = expected
            if kind == "Outcome":
                tag, value = expected
                outcome = {"kind":tag, "value" if tag == "accepted" else "error":value}
            elif kind == "Pair":
                outcome = {"first":expected[0], "second":expected[1]}
            fixtures.append({"inputs":dict(zip([a.arg for a in main.args.args], args)), "expected":outcome})
        (directory / "cases.json").write_text(json.dumps({"task_id":spec["id"], "cases":fixtures}, indent=2)+"\n", newline="\n")
    print(f"Generated {len(TASKS)} tasks, {len(TASKS)*5} adapters, {sum(len(t.cases) for t in TASKS)} cases per language.")
