def type_name(node: ast.expr) -> str:
    assert isinstance(node, ast.Name)
    return node.id

class Emitter:
    def __init__(self, lang: str, funcs: list[ast.FunctionDef]):
        self.lang = lang
        self.funcs = {f.name: f for f in funcs}
        self.vars: dict[str, str] = {}

    def typ(self, name: str) -> str:
        return TYPES[self.lang][name]

    def infer(self, n: ast.expr) -> str:
        if isinstance(n, ast.Constant):
            return "bool" if isinstance(n.value, bool) else "str" if isinstance(n.value, str) else "int"
        if isinstance(n, ast.Name):
            return self.vars[n.id]
        if isinstance(n, (ast.BoolOp, ast.Compare)):
            return "bool"
        if isinstance(n, ast.UnaryOp):
            return "bool" if isinstance(n.op, ast.Not) else "int"
        if isinstance(n, ast.BinOp):
            return self.infer(n.left)
        if isinstance(n, ast.Call):
            assert isinstance(n.func, ast.Name)
            if n.func.id in self.funcs:
                return type_name(self.funcs[n.func.id].returns)
            return {"length":"int", "at":"str", "part":"str", "contains":"bool", "lower":"str", "upper":"str", "render":"str", "accepted":"Outcome", "rejected":"Outcome", "pair":"Pair", "new_words":"Words", "push":"Words"}[n.func.id]
