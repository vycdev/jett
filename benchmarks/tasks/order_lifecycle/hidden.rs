include!("solution.rs");

#[test]
fn hidden_order_lifecycle() {
    let tests = [
        (
            OrderState::Draft,
            OrderEvent::Submit,
            TransitionResult::Accepted(OrderState::Submitted),
        ),
        (
            OrderState::Draft,
            OrderEvent::Pay,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Draft,
            OrderEvent::Ship,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Draft,
            OrderEvent::Cancel,
            TransitionResult::Accepted(OrderState::Cancelled),
        ),
        (
            OrderState::Submitted,
            OrderEvent::Submit,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Submitted,
            OrderEvent::Pay,
            TransitionResult::Accepted(OrderState::Paid),
        ),
        (
            OrderState::Submitted,
            OrderEvent::Ship,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Submitted,
            OrderEvent::Cancel,
            TransitionResult::Accepted(OrderState::Cancelled),
        ),
        (
            OrderState::Paid,
            OrderEvent::Submit,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Paid,
            OrderEvent::Pay,
            TransitionResult::Rejected(TransitionError::EventNotAllowed),
        ),
        (
            OrderState::Paid,
            OrderEvent::Ship,
            TransitionResult::Accepted(OrderState::Shipped),
        ),
        (
            OrderState::Paid,
            OrderEvent::Cancel,
            TransitionResult::Accepted(OrderState::Cancelled),
        ),
        (
            OrderState::Shipped,
            OrderEvent::Submit,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Shipped,
            OrderEvent::Pay,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Shipped,
            OrderEvent::Ship,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Shipped,
            OrderEvent::Cancel,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Cancelled,
            OrderEvent::Submit,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Cancelled,
            OrderEvent::Pay,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Cancelled,
            OrderEvent::Ship,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
        (
            OrderState::Cancelled,
            OrderEvent::Cancel,
            TransitionResult::Rejected(TransitionError::TerminalState),
        ),
    ];
    for (state, event, expected) in tests {
        assert_eq!(transition(state, event), expected);
    }
}
